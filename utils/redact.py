"""敏感信息脱敏：所有「落盘 / 对外」出口的统一过滤层。

为什么要有这一层
----------------
用户输入会同时流向三个持久化出口 ——

* 日志：``logs/agent.log``（工具入参、用户消息前 200 字、RAG query 原文）
* 对话检查点：``checkpoints.sqlite``（整轮问答全文）
* 反馈库：``feedback.sqlite``（question / answer / reason 原文）

如果每个出口各自写一遍正则，规则必然漂移，新增出口也一定会漏。所以规则
收敛成本模块的纯函数 :func:`redact`，出口只负责「调用一次」。

边界（别高估这套规则）
--------------------
1. **只做文本模式识别，不做语义理解**。带关键词前缀的地址能识别
   （"收货地址：…"、"寄到…"、"我家在…"），没有前缀的自由文本地址可能漏
   （"科技园路 1 号" 单独出现时不会处理）。图片 / PDF 里的文字不在覆盖范围。
2. **只用于存储与日志**。送给模型的输入、返回给用户的回答**不脱敏** ——
   否则"我的订单 AB****89 到哪了"这类问题根本没法处理。
3. **幂等**：掩码里含 ``*``，不会再次命中规则，重复调用不会二次破坏。
4. **绝不抛异常**：脱敏是旁路能力，失败时返回原文，不能把日志或写反馈的主
   流程带崩。

新增规则的方式
------------
在下方 PATTERNS 区加一条编译好的正则 + 一个替换函数，并按「身份证 → 银行卡
→ 手机号 → 邮箱 → 订单号 → 地址」的顺序接入 :func:`redact`。顺序有意义：
身份证必须先于银行卡，否则 18 位身份证会被 16~19 位的卡号规则先吃掉。
"""
import re

__all__ = ["redact"]


# --------------------------------------------------------------- 性能预检
# 日志每轮都要写，绝大多数内容是「即将调用模型，带有 4 条消息」这种无敏感
# 信息的文本。先跑一次廉价预检，不命中就直接返回，避免每条日志都白跑六次
# 正则。预检条件是各条规则的**必要条件**，不会漏判。
_MAYBE_SENSITIVE = re.compile(
    r"\d{11}|@|地址|住址|订单|运单|快递|物流|序列号|机身|我家在|住在|寄到|送到|发到",
    re.IGNORECASE,
)


# --------------------------------------------------------------- 身份证
# 18 位，出生年份限制在 18/19/20 开头，月日做基本范围校验 —— 这是为了把
# 普通的长数字串（订单号、流水号）排除掉，而不是做真正的校验位计算。
_ID_CARD = re.compile(
    r"(?<![0-9A-Za-z])"
    r"([1-9]\d{5})"
    r"(?:18|19|20)\d{2}"
    r"(?:0[1-9]|1[0-2])"
    r"(?:0[1-9]|[12]\d|3[01])"
    r"(\d{3}[\dXx])"
    r"(?![0-9A-Za-z])"
)


def _mask_id_card(match: re.Match) -> str:
    """保留前 6 位（地区码）与后 4 位，中间 8 位掩掉。"""
    return f"{match.group(1)}********{match.group(2)}"


# --------------------------------------------------------------- 银行卡
# 16~19 位连续数字。必须排在身份证之后：身份证掩码后含 `*`，不会再被这条
# 规则命中；反过来则会把身份证当成卡号，丢失语义。
# 副作用：18 位纯数字订单号会被当卡号处理 —— 仍然是脱敏，可接受。
_BANK_CARD = re.compile(r"(?<!\d)\d{16,19}(?!\d)")


def _mask_bank_card(match: re.Match) -> str:
    """只保留后 4 位，前 12 位连 BIN 一起掩掉。"""
    return "**** **** **** " + match.group(0)[-4:]


# --------------------------------------------------------------- 手机号
# 11 位，1 开头、第二位 3~9；前后不能紧邻数字，避免从更长的数字串中间截一段。
_PHONE = re.compile(r"(?<!\d)(1[3-9]\d)\d{4}(\d{4})(?!\d)")


# --------------------------------------------------------------- 邮箱
# 本地部分只允许「字母数字 . _ % + -」，因此掩码后的 `z***@` 不会再命中，
# 保证幂等。域名保留完整，便于运维定位是哪个域的问题。
_EMAIL = re.compile(
    r"(?<![\w.+-])"
    r"([A-Za-z0-9])[A-Za-z0-9._%+-]*"
    r"@([A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+)"
    r"(?![\w-])"
)


# --------------------------------------------------------------- 订单号
# 刻意用关键词锚定，而不是全局匹配「字母+数字」：知识库里有大量型号
# （X1 OMNI、T10 Pro），全局匹配会把产品名一起掩掉，日志就不可读了。
# 长词放前面，避免 `订单号` 先被 `订单` 抢走。
_ORDER = re.compile(
    r"(订单编号|订单号|运单号|快递单号|物流单号|序列号|SN码|SN号|机身码|订单)"
    r"(\s*(?:是|为)?\s*[:：#]?\s*)"
    r"([A-Za-z0-9][A-Za-z0-9-]{5,30})",
    re.IGNORECASE,
)


def _mask_order(match: re.Match) -> str:
    """保留前 2 后 2，中间固定四个星号（不暴露原长度）。"""
    value = match.group(3)
    return f"{match.group(1)}{match.group(2)}{value[:2]}****{value[-2:]}"


# --------------------------------------------------------------- 详细地址
# 同样是关键词锚定。必须排除 "IP地址" / "MAC地址" —— 否则网络相关的日志
# 会被误掩成 [地址已脱敏]，排查网络问题时反而看不到关键信息。
# 值部分遇到换行或标点就停止（不含冒号），避免一口气吃到下一个字段。
_ADDRESS = re.compile(
    r"(?<![Ii][Pp])(?<![Mm][Aa][Cc])(?<![Mm][Aa][Cc]\s)"
    r"(收货地址|家庭住址|单位地址|联系地址|寄回地址|退回地址|详细地址|地址|住址|所在地"
    r"|我家在|住在|寄到|送到|发到)"
    r"(\s*(?:是|在|为)?\s*[:：]?\s*)"
    r"([^\n，。；;！？!?：:]{4,60})"
)


# --------------------------------------------------------------- 对外入口

def redact(text):
    """把文本里的敏感信息替换成掩码，返回新字符串。

    :param text: 待处理文本；非字符串（None、数字等）原样返回，方便直接
                 套在可能为空的字段上。
    :return: 脱敏后的文本；任何内部异常都退回原文。

    示例::

        >>> redact("手机号 13812345678")
        '手机号 138****5678'
        >>> redact("收货地址：广东省深圳市南山区科技园路1号")
        '收货地址：[地址已脱敏]'
    """
    if not isinstance(text, str) or not text:
        return text

    if not _MAYBE_SENSITIVE.search(text):
        return text

    try:
        # 顺序不可随意调整：身份证要在银行卡之前。
        result = _ID_CARD.sub(_mask_id_card, text)
        result = _BANK_CARD.sub(_mask_bank_card, result)
        result = _PHONE.sub(r"\1****\2", result)
        result = _EMAIL.sub(r"\1***@\2", result)
        result = _ORDER.sub(_mask_order, result)
        result = _ADDRESS.sub(r"\1\2[地址已脱敏]", result)
        return result
    except Exception:
        # 脱敏是旁路：宁可漏一条，也不能让日志写入 / 反馈入库失败。
        return text
